Core Tables
Users
CREATE TABLE basavara_users (
    id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    userType   VARCHAR2(20)  NOT NULL CHECK (userType IN ('Bariwala','Varatia')),
    name       VARCHAR2(100) NOT NULL,
    phone      VARCHAR2(20)  NOT NULL,
    email      VARCHAR2(100) NOT NULL,
    birthdate  DATE          NOT NULL,
    password   VARCHAR2(64)  NOT NULL,
    is_banned  NUMBER(1)     DEFAULT 0 NOT NULL,
    ban_reason VARCHAR2(500),
    banned_at  TIMESTAMP,
    created_at TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_email UNIQUE (email),
    CONSTRAINT chk_phone CHECK (REGEXP_LIKE(phone, '^01[3-9][0-9]{8}$'))
);



House Posts
CREATE TABLE HOUSE_POST (
    POST_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OWNER_EMAIL      VARCHAR2(100) NOT NULL,
    PHONE            VARCHAR2(20)  NOT NULL,
    ADDRESS          VARCHAR2(255) NOT NULL,
    TOTAL_ROOMS      NUMBER(3) DEFAULT 1 NOT NULL CHECK (TOTAL_ROOMS > 0),
    TOTAL_WASHROOMS  NUMBER(3) DEFAULT 1 NOT NULL CHECK (TOTAL_WASHROOMS >= 0),
    DESCRIPTION      CLOB,
    VIDEO_LINK       VARCHAR2(500),
    STATUS           VARCHAR2(20) DEFAULT 'Available'
                      CHECK (STATUS IN ('Available','Rented')),
    CREATED_AT       TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_house_owner FOREIGN KEY (OWNER_EMAIL)
        REFERENCES basavara_users(email)
);
 Tenant Requests
CREATE TABLE TENANT_REQUESTS (
    REQUEST_ID    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    POST_ID       NUMBER        NOT NULL,
    TENANT_EMAIL  VARCHAR2(100) NOT NULL,
    TENANT_NAME   VARCHAR2(100) NOT NULL,
    TENANT_PHONE  VARCHAR2(20),
    REQUEST_TYPE  VARCHAR2(50) DEFAULT 'Rent Application' NOT NULL,
    DESCRIPTION   CLOB,
    STATUS        VARCHAR2(20) DEFAULT 'Pending'
                  CHECK (STATUS IN ('Pending','Approved','Rejected','Cancelled')),
    CREATED_AT    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_req_post FOREIGN KEY (POST_ID)
        REFERENCES HOUSE_POST(POST_ID) ON DELETE CASCADE,
    CONSTRAINT fk_req_tenant FOREIGN KEY (TENANT_EMAIL)
        REFERENCES basavara_users(email),
    CONSTRAINT uq_pending_req UNIQUE (POST_ID, TENANT_EMAIL, STATUS)
);
🔹 3. Feature Tables
 Complaints
CREATE TABLE COMPLAINTS (
    COMPLAINT_ID   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_EMAIL     VARCHAR2(100) NOT NULL,
    USER_TYPE      VARCHAR2(20)  NOT NULL,
    SUBJECT        VARCHAR2(200) NOT NULL,
    DESCRIPTION    CLOB          NOT NULL,
    STATUS         VARCHAR2(20) DEFAULT 'Open'
                   CHECK (STATUS IN ('Open','In Review','Resolved','Closed')),
    ADMIN_NOTE     VARCHAR2(1000),
    CREATED_AT     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_complaint_user FOREIGN KEY (USER_EMAIL)
        REFERENCES basavara_users(email) ON DELETE CASCADE
);
 Messages
CREATE TABLE MESSAGES (
    MSG_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    REQUEST_ID    NUMBER        NOT NULL,
    SENDER_EMAIL  VARCHAR2(100) NOT NULL,
    SENDER_TYPE   VARCHAR2(20)  NOT NULL,
    MESSAGE_TEXT  CLOB          NOT NULL,
    IS_READ       NUMBER(1) DEFAULT 0,
    SENT_AT       TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_msg_request FOREIGN KEY (REQUEST_ID)
        REFERENCES TENANT_REQUESTS(REQUEST_ID) ON DELETE CASCADE,
    CONSTRAINT fk_msg_sender FOREIGN KEY (SENDER_EMAIL)
        REFERENCES basavara_users(email)
);
 Notifications
CREATE TABLE NOTIFICATIONS (
    NOTIF_ID     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_EMAIL   VARCHAR2(100) NOT NULL,
    NOTIF_TYPE   VARCHAR2(50)  NOT NULL,
    TITLE        VARCHAR2(200) NOT NULL,
    BODY         VARCHAR2(1000),
    LINK_URL     VARCHAR2(500),
    IS_READ      NUMBER(1) DEFAULT 0,
    CREATED_AT   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_notif_user FOREIGN KEY (USER_EMAIL)
        REFERENCES basavara_users(email) ON DELETE CASCADE
);
 System Log
CREATE TABLE SYSTEM_LOG (
    LOG_ID     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    LOG_TIME   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    LOG_LEVEL  VARCHAR2(10) DEFAULT 'INFO'
               CHECK (LOG_LEVEL IN ('INFO','WARN','ERROR')),
    PAGE       VARCHAR2(100),
    USER_EMAIL VARCHAR2(100),
    MESSAGE    VARCHAR2(2000)
);
